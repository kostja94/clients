#!/usr/bin/env node
/**
 * Derive Frontier Rounds site brand assets from ../branding SVGs
 * and write them into the deploy repo (E:/自有部署项目/frontierrounds).
 *
 * Produces:
 *   deploy app/favicon.ico              multi-size ICO (16/32/48) — minimal black mark on transparent
 *   deploy public/favicon.ico           same (for legacy /favicon.ico requests)
 *   deploy app/icon.png                 512px black-tile white-mark  (Next convention)
 *   deploy app/apple-icon.png           180px black-tile white-mark  (Next convention)
 *   deploy public/og/og-default.png     1200x630 brand OG cover      (generated by Chrome from og.html)
 *   deploy public/og/og-default.svg     master source (kept for edits)
 *
 * Minimal favicon mark (transparent, black):
 *   open ring + upper-right gap + one escaping node, no inner chain,
 *   so it stays legible at 16 px.
 */
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const sharp = require("E:/自有部署项目/frontierrounds/node_modules/sharp");

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");                 // e:\clients\frontierrounds
const BRANDING = join(ROOT, "branding");
const DEPLOY = "E:/自有部署项目/frontierrounds";     // deploy repo root

const APP_DIR = join(DEPLOY, "app");
const PUBLIC_DIR = join(DEPLOY, "public");
const OG_DIR = join(PUBLIC_DIR, "og");

mkdirSync(APP_DIR, { recursive: true });
mkdirSync(OG_DIR, { recursive: true });

const iconSvg = readFileSync(join(BRANDING, "fr-icon.svg"), "utf8");           // black tile, white mark
const wordmarkSvg = readFileSync(join(BRANDING, "fr-wordmark.svg"), "utf8");   // black wordmark, transparent

// ---- minimal favicon mark (transparent, black) ----
function minimalFaviconSvg(size) {
  const c = size / 2;
  const ringR = size * 0.34;
  const ringW = size * 0.14;
  const gapBis = 322;                       // gap bisector (deg, y-down)
  const half = 26;                          // visible arc half-span (deg) -> gap ~52° of arc missing
  const aStart = gapBis - half;             // 296°
  const aEnd = gapBis + half;               // 348°  (arc goes long way from aStart to aEnd+360)
  const p0 = polar(c, ringR, aStart);
  const p1 = polar(c, ringR, aEnd + 360);
  const nodeR = ringW * 0.62;
  const escR = ringR + ringW / 2 + size * 0.035;
  const esc = polar(c, escR, gapBis);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}">
  <path d="M ${p0.x} ${p0.y} A ${ringR} ${ringR} 0 1 1 ${p1.x} ${p1.y}" fill="none" stroke="#000" stroke-width="${ringW}" stroke-linecap="round"/>
  <circle cx="${esc.x}" cy="${esc.y}" r="${(nodeR * 1.3).toFixed(2)}" fill="#000"/>
</svg>`;
}

function polar(c, r, deg) {
  const a = (deg * Math.PI) / 180;
  return { x: (c + r * Math.cos(a)).toFixed(2), y: (c + r * Math.sin(a)).toFixed(2) };
}

async function renderPng(svg, w, h) {
  return sharp(Buffer.from(svg), { density: 384 }).resize(w, h).png().toBuffer();
}

// build ICO (PNG-in-ICO: ICONDIR + entries + embedded PNG blobs)
function buildIco(pngs) {
  const count = pngs.length;
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);   // reserved
  header.writeUInt16LE(1, 2);   // type icon
  header.writeUInt16LE(count, 4);
  const entries = [];
  const blobs = [];
  let offset = 6 + 16 * count;
  for (const { size, png } of pngs) {
    const e = Buffer.alloc(16);
    e.writeUInt8(size >= 256 ? 0 : size, 0);
    e.writeUInt8(size >= 256 ? 0 : size, 1);
    e.writeUInt8(0, 2);
    e.writeUInt8(0, 3);
    e.writeUInt16LE(1, 4);  // planes
    e.writeUInt16LE(32, 6); // bpp
    e.writeUInt32LE(png.length, 8);
    e.writeUInt32LE(offset, 12);
    entries.push(e);
    blobs.push(png);
    offset += png.length;
  }
  return Buffer.concat([header, ...entries, ...blobs]);
}

async function rasterizeSvg(svg, w) {
  return sharp(Buffer.from(svg), { density: 384 }).resize(w, w).png().toBuffer();
}

async function main() {
  // 1) minimal favicon -> png 16/32/48 (render 256 then downscale for crispness)
  const miniSvg256 = minimalFaviconSvg(256);
  const mini256 = await renderPng(miniSvg256, 256, 256);
  const icoPngs = [];
  for (const s of [16, 32, 48]) {
    const png = await sharp(mini256).resize(s, s).png().toBuffer();
    icoPngs.push({ size: s, png });
  }
  const ico = buildIco(icoPngs);
  writeFileSync(join(APP_DIR, "favicon.ico"), ico);
  console.log("wrote app/favicon.ico");

  // 2) tile icon PNGs (black tile, white mark) — render from 1024 for quality
  const tile1024 = await rasterizeSvg(iconSvg, 1024);
  for (const [name, s] of [["app/icon.png", 512], ["app/apple-icon.png", 180]]) {
    const png = await sharp(tile1024).resize(s, s).png().toBuffer();
    writeFileSync(join(DEPLOY, name.replace("/", "\\")), png);
    console.log(`wrote ${name} (${s}px)`);
  }
  // PWA install icon at 192px lives in public/icons (manifest references it)
  const iconsDir = join(PUBLIC_DIR, "icons");
  mkdirSync(iconsDir, { recursive: true });
  const icon192 = await sharp(tile1024).resize(192, 192).png().toBuffer();
  writeFileSync(join(iconsDir, "icon-192.png"), icon192);
  console.log("wrote public/icons/icon-192.png");

  // 3) wordmark png (transparent) for OG html
  const wmPng = await rasterizeSvg(wordmarkSvg, 800);
  writeFileSync(join(OG_DIR, "_wordmark.png"), wmPng);

  // 4) full tile png for OG html
  const tilePng = await rasterizeSvg(iconSvg, 480);
  writeFileSync(join(OG_DIR, "_icon.png"), tilePng);

  // 5) write OG html + note: Chrome render step handled separately
  writeFileSync(
    join(OG_DIR, "og-default.svg"),
    `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="#F3EFE6"/>
  <text x="80" y="540" font-family="Instrument Serif, Georgia, serif" font-size="30" fill="#1A1A18">The money behind frontier AI, one round at a time.</text>
</svg>`
  );
  console.log("wrote og-default.svg (placeholder source)");
}

main().catch((e) => { console.error(e); process.exit(1); });
